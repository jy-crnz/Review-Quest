import { z } from "zod";

/**
 * Architecture is Kindness: Base fields for all entities.
 * Ensures every data object has consistent audit trails.
 */
const baseEntity = {
    id: z.string().uuid(),
    createdAt: z.coerce.date().default(() => new Date()),
    updatedAt: z.coerce.date().default(() => new Date()),
};

/**
 * NEW: Companion System Definitions
 * Validates the types of pets available in the ReviewQuest ecosystem.
 */
export const PetTypeSchema = z.enum(['cat', 'dog', 'bird', 'owl']);
export type PetType = z.infer<typeof PetTypeSchema>;

export const QuizQuestionSchema = z.object({
    q: z.string().min(1),
    options: z.array(z.string()).length(4),
    correctIdx: z.number().min(0).max(3),
    explanation: z.string().optional(),
});

export const UserSchema = z.object({
    ...baseEntity,
    username: z.string().min(3),
    email: z.string().email(),
    totalXP: z.number().nonnegative().default(0),
    level: z.number().int().positive().default(1),
    streakCount: z.number().nonnegative().default(0),

    // NEW: Persists the user's choice of Study Buddy
    selectedPet: PetTypeSchema.default('cat'),
});

export const LevelSchema = z.object({
    id: z.string(),
    topicName: z.string(),
    enemyId: z.string(),
    questions: z.array(QuizQuestionSchema),
});

export const DungeonDataSchema = z.object({
    title: z.string(),
    levels: z.array(LevelSchema),
});

export const QuizSchema = z.object({
    ...baseEntity,
    reviewerId: z.string().uuid(),

    // Personality Metadata: Defines the boss generated by the AI
    subject: z.string().optional(),
    bossName: z.string().default("The Academic Adversary"),
    bossQuote: z.string().default("Prepare to be evaluated."),

    // Narrative Metadata: Procedural Story Elements
    missionBriefing: z.string().default("Intel reveals a critical sector compromise. Your objective is to de-encrypt the target's logic gates."),
    afterActionReport: z.object({
        victory: z.string().default("Sector secured. Intelligence successfully integrated into the neural network."),
        defeat: z.string().default("Mission failed. The target has successfully encrypted their knowledge cores. Tactical retreat necessary.")
    }).default({
        victory: "Sector secured. Intelligence successfully integrated into the neural network.",
        defeat: "Mission failed. The target has successfully encrypted their knowledge cores. Tactical retreat necessary."
    }),

    questions: z.array(QuizQuestionSchema),
    timeLimit: z.number().positive().optional(),
});

export const AttemptSchema = z.object({
    ...baseEntity,
    quizId: z.string().uuid(),
    userId: z.string().uuid(),
    score: z.number().nonnegative(),
    xpEarned: z.number().nonnegative(),
    duration: z.number(), // Time in seconds
});

// Export the Types (Single Source of Truth)
// Engineering Standard: Inferring types from Zod schemas prevents type-sync bugs.
export type User = z.infer<typeof UserSchema>;
export type Quiz = z.infer<typeof QuizSchema>;
export type QuizQuestion = z.infer<typeof QuizQuestionSchema>;
export type Attempt = z.infer<typeof AttemptSchema>;
export type DungeonData = z.infer<typeof DungeonDataSchema>;
export type Level = z.infer<typeof LevelSchema>;